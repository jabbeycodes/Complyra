import { readFileSync } from "node:fs";
import { test, expect, type Page } from "./fixtures";

// Menu records: a DSP records what an Individual ate on the chart, the entry
// lands in the Mon–Sun week grid with its author, an empty week states
// "Nothing recorded", and the week's PDF carries only this Individual's
// records plus the generated-record stamp. (Clock is pinned to Saturday
// 2026-09-12 by the shared fixture.)

async function signIn(page: Page, username: string, password: string) {
  await page.goto("/");
  await page.getByLabel("Provider code").fill("EVERGREEN-MO");
  await page.getByLabel("Username").fill(username);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Sign in" }).click();
  await expect(page.getByRole("banner").or(page.locator(".topbar"))).toBeVisible({
    timeout: 10_000,
  });
}

async function openEllis(page: Page) {
  await page.getByRole("button", { name: "Individuals", exact: true }).click();
  await page.getByRole("button", { name: /Ellis Hart/ }).first().click();
  const chart = page.locator(".individual-chart");
  await expect(
    chart.getByRole("heading", { name: "Ellis Hart", exact: true }),
  ).toBeVisible();
  return chart;
}

test("DSP records breakfast, sees it in the week grid, and downloads the week PDF", async ({
  page,
}) => {
  await signIn(page, "alex.morgan", "Evergreen!demo1");
  const chart = await openEllis(page);
  const menu = chart.locator(".menu-card");
  await menu.scrollIntoViewIfNeeded();
  await expect(menu.getByRole("heading", { name: "Menu" })).toBeVisible();
  // The pinned Saturday sits in the week of Monday September 7, 2026.
  await expect(menu).toContainText("September 7");
  await expect(menu).toContainText("Nothing recorded");

  await menu.getByRole("button", { name: "Record food" }).click();
  await menu.getByLabel("Food eaten").fill("Oatmeal with berries");
  await menu.getByLabel("Amount eaten").selectOption("most");
  await menu.getByLabel("Note (optional)").fill("Ate slowly");
  await menu.getByRole("button", { name: "Save entry" }).click();

  await expect(menu).toContainText("Oatmeal with berries");
  await expect(menu).toContainText("(Most)");
  await expect(menu).toContainText("Recorded by Alex Morgan");

  // Next week is empty and says so; the way back is one click.
  await menu.getByRole("button", { name: "Next week" }).click();
  await expect(menu).toContainText("September 14");
  await expect(menu).not.toContainText("Oatmeal with berries");
  await expect(menu).toContainText("Nothing recorded");
  await menu.getByRole("button", { name: "Back to this week" }).click();
  await expect(menu).toContainText("Oatmeal with berries");

  // The downloaded week sheet is this Individual's record — and only theirs.
  const downloadPromise = page.waitForEvent("download");
  await menu.getByRole("button", { name: "Download week (PDF)" }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(
    /complyrer-menu-ellis-hart-week-2026-09-07\.pdf/,
  );
  const path = await download.path();
  const pdfText = readFileSync(path, "latin1");
  expect(pdfText).toContain("Oatmeal with berries");
  expect(pdfText).toContain("Ellis Hart");
  expect(pdfText).toContain("Digital record generated by Complyrer");
  expect(pdfText).not.toContain("Harper Soto");
  expect(pdfText).not.toContain("Morgan Pruitt");
});

test("the Menu section fits a phone-width chart with no horizontal overflow", async ({
  page,
}) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await signIn(page, "alex.morgan", "Evergreen!demo1");
  // Phone width: the chart is reached through the navigation drawer.
  await page.getByRole("button", { name: "Open navigation" }).click();
  await page
    .locator(".sidebar")
    .getByRole("button", { name: "Individuals", exact: true })
    .click();
  await page.getByRole("button", { name: /Ellis Hart/ }).first().click();
  const chart = page.locator(".individual-chart");
  await expect(
    chart.getByRole("heading", { name: "Ellis Hart", exact: true }),
  ).toBeVisible();
  const menu = chart.locator(".menu-card");
  await menu.scrollIntoViewIfNeeded();
  await expect(menu.getByRole("heading", { name: "Menu" })).toBeVisible();
  const fit = await menu.evaluate((el) => {
    const rect = el.getBoundingClientRect();
    return {
      right: rect.right,
      viewport: window.innerWidth,
      innerOverflow: el.scrollWidth - el.clientWidth,
    };
  });
  expect(fit.right).toBeLessThanOrEqual(fit.viewport);
  expect(fit.innerOverflow).toBeLessThanOrEqual(0);
});
