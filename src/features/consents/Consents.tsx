import Packets from "./Packets";
import RightsPackets from "./RightsPackets";
import { useEffect, useState } from 'react';
import { useData } from '../../data/DataProvider';
import { canManageConsents, canSeeConsents, consentDisplayText, consentOutcomeLabel, consentGaps, consentStatus, consentStatusFor, type ConsentDraft, type ConsentRegister, type ConsentType } from '../../data/consents';
import { todayStamp } from '../../data/status';
import { jsPDF } from 'jspdf';
import { openPrintable } from '../../data/openFile';
import './consents.css';
function printSummary(register: ConsentRegister, individualId: string) {
    const person = register.individuals.find(p => p.id === individualId);
    const pdf = new jsPDF();
    let y = 18;
    function line(text: string) {
        for (const part of pdf.splitTextToSize(text, 175)) {
            if (y > 270) {
                pdf.addPage();
                y = 18;
            }
            pdf.text(part, 16, y);
            y += 6;
        }
    }
    pdf.setFontSize(11);
    line('Digital record generated by Complyrer');
    line(`Consent summary: ${person?.fullName ?? 'Individual'}`);
    line(`Generated ${new Date().toISOString()}`);
    for (const type of register.types) {
        const { text: status } = consentStatusFor(register, individualId, type.id);
        line(`${type.label}: ${status}`);
        for (const r of register.records.filter(r => r.individualId === individualId && r.typeId === type.id)) {
            line(`Version ${r.id} | ${consentStatus(r, register.records, register.revocations)}`);
            line(r.covers);
            if (r.outcome)
                line(`Recorded choice: ${r.outcome}${['no', 'none'].includes(r.outcome) ? ' - Permission not given' : ''}`);
            line(`Given by ${r.giverName} (${r.giver}; ${r.relationship})`);
            line(`Signed ${r.signedOn || 'Not signed'}; effective ${r.effectiveOn}; expiry/review ${r.reviewOn}`);
            if (r.supersedesId)
                line(`Renews version ${r.supersedesId}`);
            const rev = register.revocations.find(v => v.consentId === r.id);
            if (rev)
                line(`Revoked ${rev.revokedOn} by ${rev.revokedByName}: ${rev.reason}`);
        }
    }
    void openPrintable('Consent summary.pdf', pdf.output('blob'), 'print');
}
export default function Consents({ individualId, attentionOnly = false, siteId }: {
    individualId?: string;
    attentionOnly?: boolean;
    siteId?: string | null;
}) {
    const { api, session, workspace } = useData();
    const [data, setData] = useState<ConsentRegister | null>(null);
    const [error, setError] = useState('');
    const [busy, setBusy] = useState(false);
    const [draft, setDraft] = useState<ConsentDraft | null>(null);
    const [editId, setEditId] = useState<string>();
    const [revoking, setRevoking] = useState<string | null>(null);
    const [reason, setReason] = useState('');
    const [revokedOn, setRevokedOn] = useState(todayStamp());
    const [site, setSite] = useState('');
    const [config, setConfig] = useState<ConsentType[] | null>(null);
    const role = session?.roleKey ?? '';
    const manage = canManageConsents(role);
    useEffect(() => {
        if (!canSeeConsents(role))
            return;
        let live = true;
        setData(null);
        setError('');
        api.getConsents().then(r => { if (live)
            setData(r); }).catch(e => { if (live)
            setError(e.message); });
        return () => { live = false; };
    }, [api, role, session?.userId, individualId]);
    async function run(action: () => Promise<unknown>) {
        setBusy(true);
        setError('');
        try {
            await action();
            setData(await api.getConsents());
            setDraft(null);
            setRevoking(null);
            setConfig(null);
        }
        catch (e) {
            setError(e instanceof Error ? e.message : 'Could not save consent.');
        }
        finally {
            setBusy(false);
        }
    }
    if (!canSeeConsents(role))
        return null;
    if (attentionOnly && (!manage || !data))
        return error ? <p role="alert">{error}</p> : null;
    if (attentionOnly && data) {
        const gaps = consentGaps(data).filter(g => !siteId || g.person.siteId === siteId);
        return <section className="consents"><RightsPackets attentionOnly siteId={siteId}/><Packets attentionOnly siteId={siteId}/><h2>Consents needing attention</h2>{gaps.length ? <ul>{gaps.map(g => <li key={`${g.person.id}:${g.type.id}`}><a href="#/consents">{g.person.fullName} — {g.type.label}: {g.status}</a></li>)}</ul> : <p>No missing or expiring consents in this scope.</p>}</section>;
    }
    function start(personId: string, typeId: string, prior?: ConsentDraft & {
        id: string;
    }) {
        setEditId(undefined);
        setDraft({ individualId: personId, typeId, covers: prior?.covers ?? '', giver: prior?.giver ?? 'individual', giverName: prior?.giverName ?? '', relationship: prior?.relationship ?? 'Self', signedOn: '', effectiveOn: todayStamp(), reviewOn: '', supersedesId: prior?.id ?? null, outcome: prior?.outcome });
    }
    const people = data?.individuals.filter(p => (!individualId || p.id === individualId) && (!site || p.siteId === site)) ?? [];
    return <section className="consents" id="chart-consents" aria-label="Consents register">
    <RightsPackets individualId={individualId}/><Packets individualId={individualId} onFiled={async () => setData(await api.getConsents())}/><h2>{individualId ? 'Consents and version history' : 'Consents register'}</h2>
    <p>Signed versions stay on the Individual’s chart. Renewing adds a version; revoking records who, when, and why.</p>
    {error && <p role="alert">{error}</p>}
    {!data && !error && <p role="status">Loading consents…</p>}
    {data && <>
      {!individualId && <label>Site<select value={site} onChange={e => setSite(e.target.value)}><option value="">All sites in your scope</option>{[...new Set(data.individuals.map(p => p.siteId))].map(id => <option key={id} value={id}>{workspace?.sites.find(s => s.id === id)?.name ?? id}</option>)}</select></label>}
      {role === 'program_manager' && !session?.siteId && <button disabled={busy} onClick={() => setConfig(structuredClone(data.types))}>Configure consent types</button>}
      {config && <form onSubmit={e => { e.preventDefault(); void run(() => api.saveConsentTypes(config)); }}><h3>Agency consent types</h3>
        {config.map((t, i) => <fieldset key={t.id}><legend>{t.id}</legend><label>Label<input required value={t.label} onChange={e => setConfig(config.map((x, j) => j === i ? { ...x, label: e.target.value } : x))}/></label><label><input type="checkbox" checked={t.required} onChange={e => setConfig(config.map((x, j) => j === i ? { ...x, required: e.target.checked } : x))}/>Required for each Individual</label><label><input type="checkbox" checked={t.medication} disabled={t.id === 'medication'} onChange={e => setConfig(config.map((x, j) => j === i ? { ...x, medication: e.target.checked } : x))}/>Medication consent (alerts nurses)</label></fieldset>)}
        <button type="button" onClick={() => setConfig([...config, { id: `custom_${crypto.randomUUID().slice(0, 8)}`, label: '', required: false, medication: false }])}>Add type</button><button disabled={busy}>Save agency types</button><button type="button" onClick={() => setConfig(null)}>Cancel</button></form>}
      {people.length === 0 && <p>No Individuals in your scope.</p>}
      {people.map(person => <article key={person.id}><h3>{person.fullName}</h3><button onClick={() => printSummary(data, person.id)}>Print consent summary</button>
        <div className="consent-table"><table><caption>Consent status for {person.fullName}</caption><thead><tr><th>Consent type</th><th>Status</th><th>Decision</th><th>Expiry/review</th><th>Actions and history</th></tr></thead><tbody>
        {data.types.map(type => {
                    const status = consentStatusFor(data, person.id, type.id);
                    const row = status.row;
                    const history = data.records.filter(r => r.individualId === person.id && r.typeId === type.id).sort((a, b) => b.createdAt.localeCompare(a.createdAt));
                    return <tr key={type.id}><th scope="row">{type.label}{type.required ? ' (required)' : ''}</th><td>{consentDisplayText(status, role)}</td><td>{row ? consentOutcomeLabel(row.outcome) : 'No active permission on file'}</td><td>{row?.reviewOn ?? '—'}</td><td>
            {manage && <button disabled={busy} onClick={() => start(person.id, type.id, row && row.activatedAt ? row : undefined)}>{row?.activatedAt ? 'Renew' : 'New draft'}</button>}
            <details><summary>{role === 'dsp' ? 'Active consent details' : `Version history (${history.length})`}</summary>{history.map(r => <div className="consent-version" key={r.id}>
              <p><strong>{consentStatus(r, data.records, data.revocations)}</strong> · Version {r.id}</p><p>{r.covers}</p>{r.outcome && <p><strong>Recorded choice: {r.outcome}</strong>{["no", "none"].includes(r.outcome) ? " — Permission not given" : ""}</p>}<p>Given by {r.giverName} — {r.giver}; {r.relationship}</p>
              <p>Signed {r.signedOn || 'Not signed'}; effective {r.effectiveOn}; expiry/review {r.reviewOn}</p><p>Recorded by {r.createdBy}; {r.activatedAt ? `activated ${r.activatedAt} by ${r.activatedBy ?? r.giverName}` : 'Draft'}</p>
              {r.supersedesId && <p>Renews version {r.supersedesId}</p>}
              {data.revocations.filter(v => v.consentId === r.id).map(v => <p key={v.consentId}>Revoked {v.revokedOn} by {v.revokedByName}: {v.reason}</p>)}
              {manage && !r.activatedAt && r.createdBy === session?.userId && <><button disabled={busy} onClick={() => { setEditId(r.id); setDraft({ ...r }); }}>Edit draft</button><button disabled={busy} onClick={() => void run(() => api.activateConsent(r.id))}>Activate signed consent</button></>}
              {manage && r.activatedAt && !data.revocations.some(v => v.consentId === r.id) && <button disabled={busy} onClick={() => { setRevoking(r.id); setReason(''); }}>Record revocation</button>}
            </div>)}</details>
          </td></tr>;
                })}</tbody></table></div>
      </article>)}
    </>}
    {draft && <form onSubmit={e => { e.preventDefault(); void run(() => api.saveConsent(draft, editId)); }}><h3>{editId ? 'Edit draft' : 'New consent draft'}</h3>
      <label>What the consent covers<textarea required value={draft.covers} onChange={e => setDraft({ ...draft, covers: e.target.value })}/></label>
      <label>Recorded decision<select value={draft.outcome ?? ''} onChange={e => setDraft({ ...draft, outcome: e.target.value || undefined })}><option value="">Use the consent description</option><option value="yes">Yes - permission given</option><option value="no">No - permission not given</option>{draft.typeId === 'media' && <><option value="full">Full media permission</option><option value="group">Group photographs only</option><option value="none">No media permission</option></>}</select></label>
      <label>Who gave consent<select value={draft.giver} onChange={e => setDraft({ ...draft, giver: e.target.value as ConsentDraft['giver'] })}><option value="individual">Individual</option><option value="guardian">Guardian</option><option value="representative">Authorized representative</option></select></label>
      <label>Giver’s name<input required value={draft.giverName} onChange={e => setDraft({ ...draft, giverName: e.target.value })}/></label>
      <label>Relationship<input required value={draft.relationship} onChange={e => setDraft({ ...draft, relationship: e.target.value })}/></label>
      {(['signedOn', 'effectiveOn', 'reviewOn'] as const).map((field, i) => <label key={field}>{['Signed date (required to activate)', 'Effective date', 'Expiry or review date'][i]}<input type="date" required={field !== 'signedOn'} value={draft[field]} onChange={e => setDraft({ ...draft, [field]: e.target.value })}/></label>)}
      <button disabled={busy}>Save draft</button><button type="button" disabled={busy} onClick={() => setDraft(null)}>Cancel</button>
    </form>}
    {revoking && <form onSubmit={e => { e.preventDefault(); void run(() => api.revokeConsent(revoking, revokedOn, reason)); }}><h3>Record revocation</h3><p>Recorded by {session?.fullName}. The signed consent stays in history.</p><label>Revocation date<input type="date" required value={revokedOn} onChange={e => setRevokedOn(e.target.value)}/></label><label>Reason<textarea required value={reason} onChange={e => setReason(e.target.value)}/></label><button disabled={busy}>Record revocation</button><button type="button" onClick={() => setRevoking(null)}>Cancel</button></form>}
  </section>;
}
