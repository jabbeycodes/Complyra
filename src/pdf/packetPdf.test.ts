test('blank rights packet is a complete signable form: branding, facts, signature box, footer', () => {
  const pdf = buildRightsPacketPdf(awaitingRights, 'Harper Soto', 'Evergreen Care');
  const output = pdf.output();
  assert.ok(output.includes('/XObject'), 'ComplyRer logo lockup is embedded as an image');
  for (const text of [
    'Evergreen Care',
    'Individual Rights packet',
    'Harper Soto',
    '1. Individual Rights publication',
    '2. Agency grievance process',
    '3. Agency handbook and participant rights',
    'My rights have been reviewed with me by',
    'Signatures',
    'Printed name',
    'Signature',
    'Legal authority',
    'circle one',
    'Medical Power of Attorney',
    'Witness printed name',
    'Witness signature',
    'Date',
    'Status: Awaiting signature.',
    'Digital record generated by Complyrer',
    RIGHTS_PACKET_COPY_VERSION,
    'Page 1 of 1',
  ]) {
    assert.ok(output.includes(text), text);
  }
  assert.equal(pdf.getNumberOfPages(), 1);
  assert.ok(!output.includes('[ ]'), 'no text-glyph checkboxes');
});

