/**
 * Weekly menu record for one Individual: the Mon–Sun sheet of what was
 * eaten at each meal slot, with how much was eaten and who recorded it.
 * Built from the chart's Menu section — the entries passed in are already
 * scoped to the one Individual and the one week, and the builder prints
 * exactly those rows and no others.
 */
import type { jsPDF } from "jspdf";
import {
  amountEatenLabel,
  buildMenuWeekGrid,
  menuWeekRangeLabel,
  type MenuEntryView,
} from "../data/menuRecords";
import { stampRecordMark, startBrandedDoc } from "./brandHeader";

const PAGE_BOTTOM = 750;

function slug(value: string) {
  return value
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/g, "-")
    .replaceAll(/(^-|-$)/g, "");
}

export function menuWeekFileName(individualName: string, weekStart: string) {
  return `complyrer-menu-${slug(individualName) || "individual"}-week-${weekStart}.pdf`;
}

type Cell = { text: string; width: number; header?: boolean };

function rowHeight(doc: jsPDF, cells: Cell[]): { height: number; lines: string[][] } {
  doc.setFontSize(8);
  let height = 16;
  const lines = cells.map((cell) => {
    doc.setFont("helvetica", cell.header ? "bold" : "normal");
    const wrapped = doc.splitTextToSize(cell.text || " ", Math.max(8, cell.width - 8)) as string[];
    height = Math.max(height, wrapped.length * 10 + 8);
    return wrapped;
  });
  return { height, lines };
}

function paintRow(
  doc: jsPDF,
  x: number,
  y: number,
  cells: Cell[],
  margin: number,
): number {
  const measured = rowHeight(doc, cells);
  let top = y;
  if (top + measured.height > PAGE_BOTTOM) {
    doc.addPage();
    top = margin;
  }
  let cursor = x;
  cells.forEach((cell, index) => {
    if (cell.header) {
      doc.setFillColor(236, 236, 236);
      doc.rect(cursor, top, cell.width, measured.height, "F");
    }
    doc.setDrawColor(60, 60, 60);
    doc.setLineWidth(0.4);
    doc.rect(cursor, top, cell.width, measured.height);
    doc.setFont("helvetica", cell.header ? "bold" : "normal");
    doc.setFontSize(8);
    doc.setTextColor(20, 20, 20);
    doc.text(measured.lines[index], cursor + 4, top + 11);
    cursor += cell.width;
  });
  return top + measured.height;
}

function cellText(entries: MenuEntryView[]): string {
  if (entries.length === 0) return "Nothing recorded";
  return entries
    .map((entry) => {
      const parts = [`${entry.foodText} (${amountEatenLabel(entry.amountEaten)})`];
      if (entry.note) parts.push(entry.note);
      parts.push(`Recorded by ${entry.recordedByName || "staff"}`);
      return parts.join("\n");
    })
    .join("\n\n");
}

export function buildMenuWeekPdf(input: {
  agencyName: string;
  individualName: string;
  siteName: string;
  /** Monday of the week, YYYY-MM-DD. */
  weekStart: string;
  entries: MenuEntryView[];
  generatedByName: string;
  generatedAt: string;
  logoDataUrl?: string | null;
}) {
  const { doc, margin, y: startY } = startBrandedDoc(
    `Menu record — ${input.individualName}`,
    { agencyName: input.agencyName, logoDataUrl: input.logoDataUrl ?? null },
  );
  let y = startY;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(36, 30, 24);
  doc.text(`Individual: ${input.individualName}`, margin, y);
  y += 14;
  doc.text(`Home: ${input.siteName}`, margin, y);
  y += 14;
  doc.text(`Week: ${menuWeekRangeLabel(input.weekStart)} (Monday – Sunday)`, margin, y);
  y += 22;

  const dayWidth = 64;
  const slotWidth = (612 - margin * 2 - dayWidth) / 4;
  const grid = buildMenuWeekGrid(input.entries, input.weekStart, "");

  y = paintRow(
    doc,
    margin,
    y,
    [
      { text: "Day", width: dayWidth, header: true },
      { text: "Breakfast", width: slotWidth, header: true },
      { text: "Lunch", width: slotWidth, header: true },
      { text: "Dinner", width: slotWidth, header: true },
      { text: "Snack", width: slotWidth, header: true },
    ],
    margin,
  );
  for (const day of grid) {
    y = paintRow(
      doc,
      margin,
      y,
      [
        { text: `${day.heading}\n${day.date}`, width: dayWidth, header: true },
        ...day.cells.map((cell) => ({ text: cellText(cell.entries), width: slotWidth })),
      ],
      margin,
    );
  }

  y += 16;
  doc.setFont("helvetica", "italic");
  doc.setFontSize(9);
  doc.setTextColor(95, 81, 69);
  doc.text(
    `Generated by ${input.generatedByName} · Dates are America/Chicago calendar days.`,
    margin,
    y,
  );
  doc.setTextColor(36, 30, 24);

  stampRecordMark(doc, { generatedAt: input.generatedAt, margin });
  return doc;
}
