import { test } from "node:test";
import assert from "node:assert/strict";
import { buildShiftNotesPdf, shiftNotesFileName } from "./shiftNotesPdf";
import type { ShiftNoteView } from "../data/shiftNotes";

function note(partial: Partial<ShiftNoteView> & Pick<ShiftNoteView, "id" | "noteDate" | "summary">): ShiftNoteView {
  return {
    agencyId: "a",
    individualId: "i",
    programId: "p",
    shift: "7a–3p",
    timeSpentMinutes: 60,
    staffUserId: "u",
    staffName: "Alex Morgan",
    createdAt: `${partial.noteDate}T19:00:00.000Z`,
    updatedAt: `${partial.noteDate}T19:00:00.000Z`,
    deletedAt: null,
    programName: "2026 ISP — Communication and community",
    scoringMethodName: "Yes / No",
    scores: [
      {
        id: `${partial.id}-s`,
        noteId: partial.id,
        taskId: "t",
        levelId: "yes",
        comment: "",
        taskTitle: "Use the communication device to make a choice",
      },
    ],
    ...partial,
  };
}

test("the shift-note packet names the person, the days, and the note", () => {
  const doc = buildShiftNotesPdf({
    agencyName: "Evergreen Care",
    individualName: "Ellis Hart",
    dateOfBirth: "1990-04-12",
    siteName: "Cedar House",
    programName: "2026 ISP — Communication and community",
    from: "2026-09-28",
    to: "2026-10-11",
    notes: [
      note({
        id: "n1",
        noteDate: "2026-10-02",
        summary: "Day: Ellis completed the morning routine with one prompt.",
      }),
    ],
    levelLabels: { yes: { shortLabel: "Y", caption: "Yes" } },
    generatedByName: "Sarah Mitchell",
    generatedAt: "2026-10-13T15:00:00.000Z",
  });
  const text = doc.output() as string;
  assert.ok((doc.output("blob") as Blob).size > 1500);
  assert.ok(text.includes("Clinician Report"));
  assert.ok(text.includes("Ellis Hart"));
  assert.ok(text.includes("Date of Birth"));
  assert.ok(text.includes("04/12/1990"));
  assert.ok(text.includes("Cedar House"));
  assert.ok(text.includes("Progress note"));
  assert.ok(text.includes("Waiver service"));
  assert.ok(text.includes("Signature not on this note"));
  assert.ok(text.includes("Begin Time"));
  assert.ok(text.includes("07:00 AM"));
  assert.ok(text.includes("03:00 PM"));
  assert.ok(text.includes("08:00"));
  assert.ok(text.includes("Scoring Comments"));
  assert.ok(text.includes("morning routine"));
  assert.ok(text.includes("communication device"));
  assert.ok(text.includes("Digital record generated by Complyrer"));
  assert.ok(!text.toLowerCase().includes("client"));
});

test("shift-note filename uses the person and the window", () => {
  assert.equal(
    shiftNotesFileName("Ellis Hart", "2026-09-30", "2026-10-13"),
    "complyrer-isp-notes-ellis-hart-2026-09-30-to-2026-10-13.pdf",
  );
});
