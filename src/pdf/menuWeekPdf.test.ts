import { test } from "node:test";
import assert from "node:assert/strict";
import { buildMenuWeekPdf, menuWeekFileName } from "./menuWeekPdf";
import type { MenuEntryView } from "../data/menuRecords";

function entry(partial: Partial<MenuEntryView> & Pick<MenuEntryView, "id" | "entryDate" | "mealSlot" | "foodText">): MenuEntryView {
  return {
    agencyId: "a",
    siteId: "s",
    individualId: "ellis",
    amountEaten: "all",
    note: "",
    recordedBy: "u",
    recordedByName: "Alex Morgan",
    recordedByRole: "dsp",
    createdAt: `${partial.entryDate}T13:00:00.000Z`,
    updatedAt: `${partial.entryDate}T13:00:00.000Z`,
    deletedAt: null,
    voidedBy: null,
    voidReason: "",
    ...partial,
  };
}

test("the week sheet prints the food, the amount, the recorder, and the stamp", () => {
  const doc = buildMenuWeekPdf({
    agencyName: "Evergreen Care",
    individualName: "Ellis Hart",
    siteName: "Cedar House",
    weekStart: "2026-09-07",
    entries: [
      entry({
        id: "m1",
        entryDate: "2026-09-12",
        mealSlot: "breakfast",
        foodText: "Oatmeal with berries",
        amountEaten: "most",
        note: "Ate slowly",
      }),
      entry({
        id: "m2",
        entryDate: "2026-09-12",
        mealSlot: "snack",
        foodText: "Apple slices",
        amountEaten: "some",
        recordedByName: "James Wilson",
      }),
    ],
    generatedByName: "Sarah Mitchell",
    generatedAt: "2026-09-13T15:00:00.000Z",
  });
  const text = doc.output() as string;
  assert.ok((doc.output("blob") as Blob).size > 1200);
  assert.ok(text.includes("Menu record"));
  assert.ok(text.includes("Ellis Hart"));
  assert.ok(text.includes("Cedar House"));
  assert.ok(text.includes("September 7"));
  assert.ok(text.includes("Oatmeal with berries"));
  assert.ok(text.includes("Most"));
  assert.ok(text.includes("Ate slowly"));
  assert.ok(text.includes("Apple slices"));
  assert.ok(text.includes("Recorded by Alex Morgan"));
  assert.ok(text.includes("Recorded by James Wilson"));
  assert.ok(text.includes("Nothing recorded")); // empty slots are stated, not blank
  assert.ok(text.includes("Digital record generated by Complyrer"));
  assert.ok(!text.toLowerCase().includes("client"));
  assert.ok(!text.toLowerCase().includes("patient"));
});

test("the week sheet contains only the entries it was given", () => {
  const doc = buildMenuWeekPdf({
    agencyName: "Evergreen Care",
    individualName: "Ellis Hart",
    siteName: "Cedar House",
    weekStart: "2026-09-07",
    entries: [
      entry({ id: "m1", entryDate: "2026-09-08", mealSlot: "lunch", foodText: "Tomato soup" }),
    ],
    generatedByName: "Sarah Mitchell",
    generatedAt: "2026-09-13T15:00:00.000Z",
  });
  const text = doc.output() as string;
  assert.ok(text.includes("Tomato soup"));
  // Another Individual's food (never passed to the builder) cannot appear.
  assert.ok(!text.includes("Harper Soto"));
  assert.ok(!text.includes("Grilled salmon"));
});

test("voided entries never print", () => {
  const doc = buildMenuWeekPdf({
    agencyName: "Evergreen Care",
    individualName: "Ellis Hart",
    siteName: "Cedar House",
    weekStart: "2026-09-07",
    entries: [
      entry({
        id: "m9",
        entryDate: "2026-09-09",
        mealSlot: "dinner",
        foodText: "Voided lasagna",
        deletedAt: "2026-09-09T23:00:00.000Z",
        voidReason: "Recorded twice",
      }),
    ],
    generatedByName: "Sarah Mitchell",
    generatedAt: "2026-09-13T15:00:00.000Z",
  });
  const text = doc.output() as string;
  assert.ok(!text.includes("Voided lasagna"));
});

test("the filename carries the person and the week", () => {
  assert.equal(
    menuWeekFileName("Ellis Hart", "2026-09-07"),
    "complyrer-menu-ellis-hart-week-2026-09-07.pdf",
  );
});
