import { jsPDF } from 'jspdf';
import {
    RIGHTS_PACKET_ACKNOWLEDGEMENTS,
    addOneYear,
    type RightsPacket,
} from '../data/rightsPackets';

/**
 * The Rights packet document — the printable version of the chart
 * record, generated on demand. Blank signer lines when the packet is
 * still awaiting signature; the recorded values once completed. Every
 * page carries the platform's record stamp.
 */
export function buildRightsPacketPdf(packet: RightsPacket, individualName: string, agencyName: string) {
    const pdf = new jsPDF();
    let y = 22;
    const stamp = () => {
        pdf.setFontSize(9);
        pdf.text('Digital record generated by Complyrer', 16, 12);
        pdf.text(packet.copyVersion, 16, 286);
    };
    const line = (text: string, size = 11) => {
        pdf.setFontSize(size);
        for (const part of pdf.splitTextToSize(text, 176)) {
            if (y > 265) {
                pdf.addPage();
                y = 22;
                stamp();
            }
            pdf.text(part, 16, y);
            y += 6;
        }
        y += 2;
    };
    stamp();
    line('Individual Rights packet', 18);
    line(`Individual: ${individualName}`);
    line(`Agency: ${agencyName}`);
    for (const item of RIGHTS_PACKET_ACKNOWLEDGEMENTS) {
        line(item.heading, 13);
        line(item.text);
    }
    const signer = packet.signer;
    line(`My rights have been reviewed with me by: ${packet.reviewedBy || '________________________________'}`);
    line(`Printed name of Individual: ${individualName}`);
    line(`Signer printed name: ${signer?.printedName ?? packet.signerName ?? '________________________________'}`);
    line(`Signature: ${signer?.signature ?? '____________________________________'}`);
    line(`Legal authority: ${signer ? signer.authority + (signer.authorityOther ? ': ' + signer.authorityOther : '') : 'Self / Parent / Guardian / Medical Power of Attorney / Other: __________'}`);
    line(`Witness: ${signer?.witness ?? '____________________________________'}`);
    line(`Date: ${packet.packetOn ?? '________________'}`);
    if (packet.packetOn) {
        line(`Packet date ${packet.packetOn} · Annual renewal due ${addOneYear(packet.packetOn)}`);
        line(`Status: ${packet.status === 'filed' ? 'Signed paper copy filed' : 'Signed'} (recorded ${packet.signedAt?.slice(0, 10) ?? ''}).`);
    }
    else {
        line('Status: Awaiting signature.');
    }
    return pdf;
}
