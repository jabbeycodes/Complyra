import { test } from 'node:test';
import assert from 'node:assert/strict';
import { LocalApi, MemoryStore } from './localApi';
import { createEvergreenSeed } from './seed';
import { PACKET_ITEMS, validatePacketSubmission, packetStatus, packetOutstanding, tokenHash, type PacketChoices, type PacketSignature } from './consentPackets';
import { todayStamp } from './status';
import { buildConsentPacketPdf } from '../pdf/consentPacketPdf';
const choices: PacketChoices = Object.fromEntries(PACKET_ITEMS.map(i => [i.key, i.key === 'media' ? 'group' : i.key === 'photograph' ? 'no' : 'yes']));
const signer: PacketSignature = { printedName: 'Jordan Lee', signature: 'Jordan Lee', authority: 'Guardian', authorityOther: '', witness: 'Taylor Witness', signedOn: todayStamp(), accepted: true };
function setup() {
    const db = createEvergreenSeed();
    const store = new MemoryStore(db);
    const api = new LocalApi(store);
    const hm = db.memberships.find(m => m.roleKey === 'house_manager')!;
    store.sessionUserId = hm.userId;
    const person = db.individuals.find(p => p.siteId === hm.siteId)!;
    return { db, store, api, hm, person, input: { individualId: person.id, signerName: 'Jordan Lee', effectiveOn: todayStamp(), reviewOn: '2099-12-31', outstandingAfterDays: 1 } };
}
test('packet token isolates one packet, hashes at rest, records open/sign trail and refuses replay', async () => {
    const f = setup();
    const first = await f.api.createConsentPacket(f.input);
    const other = await f.api.createConsentPacket(f.input);
    await f.api.generateConsentPacket(first);
    const token = await f.api.sendConsentPacket(first, 7);
    assert.match(token, /^[0-9a-f]{64}$/);
    assert.equal(f.db.consentPacketTokens?.[first].hash, await tokenHash(token));
    assert.ok(!JSON.stringify(await f.api.listConsentPackets()).includes(token));
    const publicView = await f.api.openConsentPacket(token);
    assert.equal(publicView.id, first);
    assert.deepEqual(Object.keys(publicView).sort(), ['id', 'snapshot']);
    assert.equal(f.db.consentPackets?.find(p => p.id === other)?.openedAt, null);
    f.store.sessionUserId = null;
    const evidence = await f.api.signConsentPacket(token, choices, signer);
    assert.equal(evidence.mime, 'application/pdf');
    assert.ok(atob(evidence.base64).startsWith('%PDF-'));
    // Scoped to this packet's records: the demo seed carries other consents.
    assert.equal(f.db.consents?.filter(r => r.packetId === first).length, 9);
    assert.equal(f.db.consents?.find(r => r.packetId === first && r.typeId === 'photograph')?.outcome, 'no');
    assert.equal(f.db.consents?.find(r => r.packetId === first && r.typeId === 'media')?.outcome, 'group');
    assert.equal(f.db.consentPackets?.find(p => p.id === other)?.status, 'draft');
    assert.ok(f.db.consentPacketAudit?.some(e => e.event === 'opened'));
    assert.ok(f.db.consentPacketAudit?.some(e => e.event === 'signed' && e.signerName === signer.printedName));
    await assert.rejects(() => f.api.signConsentPacket(token, choices, signer), /unavailable/);
    await assert.rejects(() => f.api.openConsentPacket(token), /unavailable/);
    f.store.sessionUserId = f.hm.userId;
    await assert.rejects(() => f.api.generateConsentPacket(first), /immutable/);
    await assert.rejects(() => f.api.sendConsentPacket(first, 7), /immutable/);
    assert.equal((await f.api.listNotifications()).filter(n => n.type === 'consent.packet_signed').length, 1);
});
test('expired and replaced tokens fail, outstanding uses configured window, alerts dedupe', async () => {
    const f = setup();
    const id = await f.api.createConsentPacket(f.input);
    await f.api.generateConsentPacket(id);
    const old = await f.api.sendConsentPacket(id, 7);
    const token = await f.api.sendConsentPacket(id, 7);
    await assert.rejects(() => f.api.openConsentPacket(old), /unavailable/);
    const packet = f.db.consentPackets!.find(p => p.id === id)!;
    packet.sentAt = '2020-01-01T00:00:00Z';
    assert.ok(packetOutstanding(packet));
    await f.api.listNotifications();
    const count = f.db.notifications.filter(n => n.type === 'consent.packet_outstanding').length;
    assert.ok(count > 0);
    await f.api.listNotifications();
    assert.equal(f.db.notifications.filter(n => n.type === 'consent.packet_outstanding').length, count);
    packet.linkExpiresAt = '2020-01-02T00:00:00Z';
    f.db.consentPacketTokens![id].expiresAt = packet.linkExpiresAt;
    assert.equal(packetStatus(packet), 'expired');
    await assert.rejects(() => f.api.openConsentPacket(token), /expired/);
    await assert.rejects(() => f.api.signConsentPacket(token, choices, signer), /expired/);
});
test('paper route requires signed evidence and confirmed choices, creates same nine records and preserves copy', async () => {
    const f = setup();
    const id = await f.api.createConsentPacket(f.input);
    await f.api.generateConsentPacket(id);
    const pdf = buildConsentPacketPdf(f.db.consentPackets!.find(p => p.id === id)!.snapshot, choices, signer);
    const file = new File([pdf.output('arraybuffer')], 'paper.pdf', { type: 'application/pdf' });
    await assert.rejects(() => f.api.filePaperConsentPacket(id, choices, { ...signer, accepted: false }, file), /agreement/);
    await assert.rejects(() => f.api.filePaperConsentPacket(id, choices, signer, new File(['fake'], 'bad.pdf', { type: 'application/pdf' })), /content/);
    await f.api.filePaperConsentPacket(id, choices, signer, file);
    // Scoped to this packet's records: the demo seed carries other consents.
    assert.equal(f.db.consents?.filter(r => r.packetId === id).length, 9);
    assert.equal((await f.api.getConsentPacketEvidence(id)).name, 'paper.pdf');
    assert.ok(f.db.consents?.filter(r => r.packetId === id).every(r => r.activatedBy === f.hm.userId));
    await assert.rejects(() => f.api.filePaperConsentPacket(id, choices, signer, file), /immutable/);
});
test('packet signing needs every explicit choice, authority and witness; PDF carries original sections and stamp', async () => {
    assert.throws(() => validatePacketSubmission({ ...choices, media: '' }, signer), /answer/);
    assert.throws(() => validatePacketSubmission(choices, { ...signer, authority: 'Other', authorityOther: '' }), /authority/);
    assert.throws(() => validatePacketSubmission(choices, { ...signer, witness: '' }), /witness/);
    validatePacketSubmission(choices, signer);
    const f = setup();
    const packetId = await f.api.createConsentPacket(f.input);
    const pdf = buildConsentPacketPdf(f.db.consentPackets!.find(p => p.id === packetId)!.snapshot, choices, signer);
    const output = pdf.output();
    assert.ok(pdf.getNumberOfPages() >= 5);
    for (const text of ['Digital record generated by Complyrer', 'Evergreen Care', 'Service and treatment decisions', 'Health information exchange', 'Rights information and questions', 'Public media choices', 'Jordan Lee', 'Recorded choice: group']) assert.ok(output.includes(text), text);
    assert.equal(PACKET_ITEMS.length, 9);
});

test('packet filing supersedes an existing standalone decision and DSPs receive only the replacement', async () => {
    const f = setup();
    const previous = await f.api.saveConsent({individualId:f.person.id,typeId:'media',covers:'No media permission.',giver:'individual',giverName:f.person.fullName,relationship:'Self',outcome:'none',signedOn:todayStamp(),effectiveOn:todayStamp(),reviewOn:'2099-12-31',supersedesId:null});
    await f.api.activateConsent(previous);
    const id = await f.api.createConsentPacket(f.input);
    await f.api.generateConsentPacket(id);
    const token = await f.api.sendConsentPacket(id,7);
    await f.api.signConsentPacket(token,choices,signer);
    const replacement = f.db.consents!.find(r => r.packetId===id && r.typeId==='media')!;
    assert.equal(replacement.supersedesId,previous);
    f.store.sessionUserId = f.db.memberships.find(m => m.roleKey==='dsp' && m.siteId===f.person.siteId)!.userId;
    assert.deepEqual((await f.api.getConsents()).records.filter(r => r.individualId===f.person.id && r.typeId==='media').map(r => r.id),[replacement.id]);
});
