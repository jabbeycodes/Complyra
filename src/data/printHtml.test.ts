import assert from "node:assert/strict";
import test from "node:test";
import { brandedPrintHtml } from "./printHtml";

const LOGO =
  "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==";

test("brandedPrintHtml carries the agency logo, name, and Complyrer header + footer", () => {
  const html = brandedPrintHtml({
    brand: { agencyName: "Evergreen Care", logoDataUrl: LOGO },
    title: "Behavior log — Harper Soto",
    styles: "table{border-collapse:collapse}",
    bodyHtml: "<h1>Behavior log — Harper Soto</h1><table></table>",
  });
  assert.ok(html.includes(`<img src="${LOGO}"`), "logo renders in the header");
  assert.ok(html.includes("Evergreen Care"), "agency name renders in the header");
  assert.ok(html.includes("Prepared with Complyrer"), "Complyrer line renders in the header");
  assert.ok(
    html.includes("Digital record generated by Complyrer."),
    "record mark renders as the footer",
  );
  assert.ok(
    html.includes("<h1>Behavior log — Harper Soto</h1><table></table>"),
    "body markup passes through unchanged",
  );
  assert.ok(html.includes("table{border-collapse:collapse}"), "caller styles are kept");
});

test("brandedPrintHtml without a logo keeps the agency name and mark", () => {
  const html = brandedPrintHtml({
    brand: { agencyName: "Evergreen Care", logoDataUrl: null },
    title: "Event report — Harper Soto",
    bodyHtml: "<h1>Event report</h1>",
  });
  assert.ok(!html.includes("<img"), "no logo image when the agency has none set");
  assert.ok(html.includes("Evergreen Care"));
  assert.ok(html.includes("Digital record generated by Complyrer."));
});

test("brandedPrintHtml escapes the agency name and title", () => {
  const html = brandedPrintHtml({
    brand: { agencyName: "A & B <Care>", logoDataUrl: null },
    title: "Log — A & B",
    bodyHtml: "<p>x</p>",
  });
  assert.ok(html.includes("A &amp; B &lt;Care&gt;"));
  assert.ok(html.includes("<title>Log — A &amp; B</title>"));
});
