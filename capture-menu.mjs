import { chromium } from "playwright";
const base = process.env.BASE || "http://localhost:4317";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
await page.goto(base + "/");
await page.getByLabel("Provider code").fill("EVERGREEN-MO");
await page.getByLabel("Username").fill("alex.morgan");
await page.getByLabel("Password", { exact: true }).fill("Evergreen!demo1");
await page.getByRole("button", { name: "Sign in" }).click();
await page.locator(".topbar").waitFor({ timeout: 15000 });
await page.getByRole("button", { name: "Individuals", exact: true }).click();
await page.getByRole("button", { name: /Ellis Hart/ }).first().click();
const chart = page.locator(".individual-chart");
await chart.getByRole("heading", { name: "Ellis Hart", exact: true }).waitFor();
const menu = chart.locator(".menu-card");
await menu.scrollIntoViewIfNeeded();
await menu.getByRole("button", { name: "Record food" }).click();
await menu.getByLabel("Food eaten").fill("Oatmeal with berries");
await menu.getByLabel("Amount eaten").selectOption("most");
await menu.getByLabel("Note (optional)").fill("Ate slowly");
await menu.getByRole("button", { name: "Save entry" }).click();
await page.waitForFunction(() => document.querySelector(".menu-card")?.textContent?.includes("Oatmeal with berries"), null, { timeout: 10000 });
await menu.scrollIntoViewIfNeeded();
await page.waitForTimeout(400);
await menu.screenshot({ path: "/home/hatch/workspace/menu-records-mobile-shot.png" });
console.log("captured");
await browser.close();
