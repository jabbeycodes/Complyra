import type { PacketChoices, PacketSignature, PacketSnapshot } from './consentPacketContent.ts';
// A structural interface lets browser jsPDF and the server's npm jsPDF use the
// exact same original packet layout, without a browser-controlled signed PDF.
interface PdfDocument {
    setFontSize(n: number): unknown;
    text(s: string, x: number, y: number): unknown;
    splitTextToSize(s: string, w: number): string[];
    addPage(): unknown;
}
export function drawConsentPacket(pdf: PdfDocument, snapshot: PacketSnapshot, choices?: PacketChoices | null, signer?: PacketSignature | null) {
    let y = 22;
    const page = () => { pdf.addPage(); y = 22; stamp(); };
    const stamp = () => { pdf.setFontSize(9); pdf.text('Digital record generated by Complyrer', 16, 12); pdf.text(snapshot.copyVersion, 16, 286); };
    const line = (text: string, size = 11) => { pdf.setFontSize(size); for (const part of pdf.splitTextToSize(text, 176)) {
        if (y > 265)
            page();
        pdf.text(part, 16, y);
        y += 6;
    } y += 2; };
    const signature = () => {
        line(`Printed name: ${signer?.printedName ?? '________________________________'}`);
        line(`Signature: ${signer?.signature ?? '____________________________________'}`);
        line(`Authority: ${signer ? signer.authority + (signer.authorityOther ? ': ' + signer.authorityOther : '') : 'Self / Parent / Guardian / Medical Power of Attorney / Other: __________'}`);
        line(`Witness: ${signer?.witness ?? '____________________________________'}   Date: ${signer?.signedOn ?? '________________'}`);
    };
    stamp();
    line('Consent choices and signature record', 18);
    line(`Individual: ${snapshot.individualName}`);
    line(`Agency: ${snapshot.agencyName}`);
    line(`Expected signer: ${snapshot.signerName}`);
    line(`Effective: ${snapshot.effectiveOn}   Expiry/review: ${snapshot.reviewOn}`);
    line('This packet records separate decisions. A No answer or no media permission is a recorded decision, not permission to proceed. Keep a copy of the completed packet.');
    line('Packet contents: service decisions, health information exchange, rights information, and public media choices. Each section has its own signature record.');
    for (const section of [
        { title: 'Service and treatment decisions', keys: ['participation', 'photograph', 'medications', 'emergency', 'outings', 'law_enforcement'] },
        { title: 'Health information exchange', keys: ['information'] },
        { title: 'Rights information and questions', keys: ['rights'] },
        { title: 'Public media choices', keys: ['media'] },
    ]) {
        page();
        line(section.title, 16);
        for (const key of section.keys) {
            const item = snapshot.items.find(i => i.key === key)!;
            line(item.label, 13);
            line(item.text);
            if (key === 'information')
                for (const scope of snapshot.healthScope)
                    line(`- ${scope}`);
            line(choices ? `Recorded choice: ${choices[key]}` : key === 'media' ? '[ ] Full permission   [ ] Group photographs only   [ ] No permission' : '[ ] Yes   [ ] No');
        }
        signature();
    }
    if (signer) {
        line('The signer confirmed these choices and agreed that the entered signature records their intent for each section above.');
    }
    return pdf;
}
