/**
 * Generate a permission seed-refresh migration from src/data/permissions.ts.
 *
 * Usage:
 *   npx tsx scripts/generate-permission-seed-refresh.ts <migration-file-name> "<reason>"
 *
 * Writes supabase/migrations/<migration-file-name> that upserts the canonical
 * role_permission_matrix + role_templates rows for every role in
 * ROLE_TEMPLATES, then lets stored template/agency copies inherit canonical
 * capabilities they lack (existing agency choices win — the established seed
 * pattern from 20260915024000 and 20261031310000).
 *
 * Run it whenever PERMISSION_KEYS or a role template changes, and point
 * LATEST_SEED_MIGRATION_PATH in src/data/permissionTruth.test.ts at the new
 * file. The newest refresh must always be the LAST migration that seeds the
 * matrix, or an older generated seed can overwrite newer grants.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROLE_TEMPLATES } from "../src/data/permissions";

const [fileName, reason] = process.argv.slice(2);
if (!fileName || !/^\d{14}_[a-z0-9_]+\.sql$/.test(fileName) || !reason) {
  console.error(
    'Usage: npx tsx scripts/generate-permission-seed-refresh.ts <YYYYMMDDHHMMSS_name.sql> "<reason>"',
  );
  process.exit(1);
}

const sql = (value: string) => `'${value.replaceAll("'", "''")}'`;
const json = (value: unknown) => `${sql(JSON.stringify(value))}::jsonb`;

const matrixRows = ROLE_TEMPLATES.map(
  (role) => `(${sql(role.key)}, ${json(role.permissions)})`,
).join(",\n");

const templateRows = ROLE_TEMPLATES.map(
  (role) =>
    `(${[
      sql(role.key),
      sql(role.name),
      sql(role.shortCode),
      sql(role.description),
      sql(role.defaultScope),
      sql(role.capability),
      json(role.permissions),
    ].join(", ")})`,
).join(",\n");

const today = new Date().toISOString().slice(0, 10);
const body = `-- Permission seed refresh — generated by
-- scripts/generate-permission-seed-refresh.ts from src/data/permissions.ts
-- (ROLE_TEMPLATES), ${today}.
--
-- Why: ${reason}
--
-- This file is the latest seed refresh for the permission-truth tests
-- (LATEST_SEED_MIGRATION_PATH in src/data/permissionTruth.test.ts).
-- Idempotent: both inserts are upserts and the inherit updates only add
-- canonical keys a stored copy lacks; existing agency choices win.

insert into public.role_permission_matrix (role_key, permissions)
values
${matrixRows}
on conflict (role_key) do update set
  permissions = excluded.permissions,
  updated_at = now();

insert into public.role_templates
  (key, name, short_code, description, default_scope, capability, permissions)
values
${templateRows}
on conflict (key) do update set
  name = excluded.name,
  short_code = excluded.short_code,
  description = excluded.description,
  default_scope = excluded.default_scope,
  capability = excluded.capability,
  permissions = excluded.permissions;

-- Missing canonical capabilities inherit their defaults in stored copies;
-- existing agency choices win (the established seed pattern).
update public.role_templates t set permissions = m.permissions || t.permissions
from public.role_permission_matrix m where m.role_key = t.key;
update public.agency_roles a set permissions = m.permissions || a.permissions
from public.role_permission_matrix m where m.role_key = a.template_key;
`;

const target = join("supabase", "migrations", fileName);
writeFileSync(target, body);
console.log(`Wrote ${target} (${ROLE_TEMPLATES.length} roles).`);
